md_append_bias <- function(tbl, title) {
  tbl <- tbl[order(factor(tbl$prior_bin, levels = prior_bin_labels)), ]
  header <- "| Prior Bin | Mean | SD | N |"
  sep    <- "|-----------|-----:|---:|--:|"
  rows   <- sprintf("| %s | %.4f | %.4f | %d |",
                    tbl$prior_bin, tbl$Mean, tbl$SD, tbl$N)
  lines  <- c(paste0("## ", title), "", header, sep, rows, "")
  cat(lines, sep = "\n", append = TRUE, file = md_path)
}

md_append_cd <- function(cd_long, group_var, bins_ordered, title) {
  sig_types <- c("Regular", "Retraction", "Confirmation")

  for (param_name in c("c", "d")) {
    param_title <- if (param_name == "c") "Base-Rate Use (c)" else "Inference (d)"
    header <- paste0("| ", tools::toTitleCase(gsub("_"," ",group_var)),
                     " | Regular | Retraction | Confirmation |")
    sep    <- paste0("|", paste(rep("---|", 4), collapse=""))

    rows <- vapply(bins_ordered, function(g) {
      get_val <- function(sig) {
        row <- cd_long[cd_long[[group_var]] == g &
                         cd_long$param == param_name &
                         cd_long$signal_type == sig, ]
        if (nrow(row) == 0 || is.na(row$estimate[1]))
          return("---")
        sprintf("%.3f (%.3f)", row$estimate[1], row$std.error[1])
      }
      paste0("| ", g, " | ", get_val("Regular"), " | ",
             get_val("Retraction"), " | ", get_val("Confirmation"), " |")
    }, character(1))

    lines <- c(paste0("### ", title, " — ", param_title),
               "", header, sep, rows, "")
    cat(lines, sep = "\n", append = TRUE, file = md_path)
  }
}



