# HELPER: LaTeX table — mean, SD, N by bin
######################################################
write_mean_sd_tex <- function(tbl, out_path, caption, label,
                               col_label = "Mean Bias") {
  # tbl must have columns: prior_bin, Mean, SD, N
  tbl <- tbl[order(factor(tbl$prior_bin, levels = prior_bin_labels)), ]

  lines <- c(
    "\\begin{table}[htbp]",
    "\\centering",
    paste0("\\caption{", caption, "}"),
    paste0("\\label{", label, "}"),
    "\\begin{tabular}{lrrr}",
    "\\hline",
    paste0("Prior Bin & ", col_label, " & SD & $N$ \\\\"),
    "\\hline"
  )
  for (i in seq_len(nrow(tbl))) {
    lines <- c(lines,
      sprintf("%s\\%% & %.4f & %.4f & %d \\\\",
              as.character(tbl$prior_bin[i]),
              tbl$Mean[i], tbl$SD[i], tbl$N[i])
    )
  }
  lines <- c(lines, "\\hline",
    paste0("\\multicolumn{4}{l}{\\small SD is descriptive (raw distribution).",
           " $N$ = observations per bin.} \\\\"),
    "\\end{tabular}", "\\end{table}"
  )
  writeLines(lines, out_path)
  invisible(tbl)
}


######################################################
# HELPER: TikZ bias-bar figure (for mean bias plots)
#
# tbl: data.frame with columns prior_bin, Mean, SD (10 rows)
# overreact_label_side: "above" if positive = overreact,
#                        "below" if positive = underreact (like retraction TikZ)
######################################################
write_tikz_bias <- function(tbl, out_path, ylabel,
                             positive_label = "Overreacts") {
  tbl <- tbl[order(factor(tbl$prior_bin, levels = prior_bin_labels)), ]
  bin_mids <- seq(0.05, 0.95, 0.1)

  # y-axis range: cover mean ± SD, always include zero
  y_lo <- min(c(0, tbl$Mean - tbl$SD), na.rm = TRUE)
  y_hi <- max(c(0, tbl$Mean + tbl$SD), na.rm = TRUE)
  pad  <- max(abs(c(y_lo, y_hi))) * 0.2
  y_lo <- floor((y_lo - pad) * 10) / 10
  y_hi <- ceiling((y_hi + pad) * 10) / 10

  neg_label <- if (positive_label == "Overreacts") "Underreacts" else "Overreacts"

  # Position for Overreacts/Underreacts labels (60% of positive/negative range)
  pos_mid <- y_hi * 0.6
  neg_mid <- y_lo * 0.6

  lines <- c(
    paste0("% Auto-generated by 04_additional_analysis.R — do not edit"),
    paste0("% y > 0: ", positive_label, "  |  y < 0: ", neg_label),
    "\\begin{tikzpicture}[scale=12]",
    sprintf("\\draw[help lines,step=0.1] (0,%.1f) grid (1,%.1f);", y_lo, y_hi)
  )

  for (i in 1:10) {
    m <- tbl$Mean[i]
    s <- tbl$SD[i]
    if (is.na(m) || is.na(s)) next
    x <- bin_mids[i]
    lines <- c(lines,
      sprintf("\\filldraw[opaque,white!80!black] (%.2f,0) rectangle (%.2f,%.4f);",
              x - 0.02, x + 0.02, m),
      sprintf("\\draw[line width=0.6] (%.2f,0) rectangle (%.2f,%.4f);",
              x - 0.02, x + 0.02, m),
      sprintf("\\draw[line width=0.6,|-|] (%.2f,%.4f) -- (%.2f,%.4f);",
              x, m - s, x, m + s)
    )
  }

  lines <- c(lines,
    sprintf("\\draw[line width=0.8,->]  (0,0) -- (1.1,0) node[below] {\\small{$p_{t-1}(R)$}};"),
    sprintf("\\draw[line width=0.8,<->] (0,%.1f) -- (0,%.1f) node[above] {%s};",
            y_lo, y_hi, ylabel),
    sprintf("\\draw (0,%.2f) node[above,rotate=90] {\\small{%s}};",
            pos_mid, positive_label),
    sprintf("\\draw (0,%.2f) node[above,rotate=90] {\\small{%s}};",
            neg_mid, neg_label),
    "% ADD THEORY CURVE BELOW IF NEEDED:",
    "% \\draw[red,line width=1.2,domain=0.01:0.99] plot(\\x,{...});",
    "\\end{tikzpicture}"
  )
  writeLines(lines, out_path)
  invisible(tbl)
}


